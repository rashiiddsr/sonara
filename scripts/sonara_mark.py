"""Generates every size of the SONARA mark (see docs/design.md). Run from the repository root.

The mark: a rounded play triangle sending out two echo arcs, teal on the night. One geometry on
a 72-unit grid; every file below is a scaled copy of it.
"""
import math

RES = "app/src/main/res/"
TEAL = "#FF2EE6C5"
NIGHT = "#FF0A0B0D"
BADGE = "#FF12161A"
HEAD = "<!-- SONARA mark: a play button sending out its echo. Original artwork (GPL-3.0). Generated by scripts/sonara_mark.py. -->"

TRIANGLE = [(17, 22), (17, 50), (39, 36)]
ECHO_CENTER = (34.5, 36)
ECHOES = [(13, 44, 0.8), (21, 46, 0.45)]  # radius, half angle, alpha


def tf(x, y, cx, cy, k):
    return f"{cx + (x - 36) * k:.2f},{cy + (y - 36) * k:.2f}"


def triangle(cx, cy, k):
    a, b, c = (tf(x, y, cx, cy, k) for x, y in TRIANGLE)
    return f"M{a}L{b}L{c}Z"


def echo(cx, cy, k, r, half):
    ox, oy = ECHO_CENTER
    p0 = tf(ox + r * math.cos(math.radians(-half)), oy + r * math.sin(math.radians(-half)), cx, cy, k)
    p1 = tf(ox + r * math.cos(math.radians(half)), oy + r * math.sin(math.radians(half)), cx, cy, k)
    return f"M{p0}A{r * k:.2f},{r * k:.2f} 0,0 1,{p1}"


def mark(cx, cy, k, color, indent=4, names=False, hidden=False):
    pad = " " * indent
    n = ' android:name="play"' if names else ""
    invisible = ' android:fillAlpha="0" android:strokeAlpha="0"' if hidden else ""
    out = (f'{pad}<path{n} android:pathData="{triangle(cx, cy, k)}"\n'
           f'{pad}    android:fillColor="{color}" android:strokeColor="{color}" android:strokeWidth="{3 * k:.2f}"\n'
           f'{pad}    android:strokeLineJoin="round"{invisible} />\n')
    for i, (r, half, alpha) in enumerate(ECHOES):
        n = f' android:name="echo{i}"' if names else ""
        out += (f'{pad}<path{n} android:pathData="{echo(cx, cy, k, r, half)}"\n'
                f'{pad}    android:strokeColor="{color}" android:strokeWidth="{3.6 * k:.2f}" android:strokeLineCap="round"\n'
                f'{pad}    android:strokeAlpha="{0 if hidden else alpha}" />\n')
    return out


def rounded_square(size, radius, color):
    r = radius
    s = size
    return (f'    <path android:fillColor="{color}" android:pathData="M{r},0H{s - r}A{r},{r} 0,0 1,{s},{r}V{s - r}'
            f'A{r},{r} 0,0 1,{s - r},{s}H{r}A{r},{r} 0,0 1,0,{s - r}V{r}A{r},{r} 0,0 1,{r},0Z" />\n')


def vector(size_dp, viewport, body):
    return (f'<?xml version="1.0" encoding="utf-8"?>\n{HEAD}\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size_dp}dp" android:height="{size_dp}dp"\n'
            f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n{body}</vector>\n')


def write(name, text):
    with open(RES + "drawable/" + name, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


# In-app badge (top bar, sign-in, lyrics card): the mark on a dark rounded square.
badge = rounded_square(72, 18, BADGE) + mark(36, 36, 1, TEAL)
write("app_logo.xml", vector(24, 72, badge))
write("logo_mark.xml", vector(28, 72, badge))
# Notification: the mark alone, white.
write("small_icon.xml", vector(24, 72, mark(36, 36, 1.12, "#FFFFFFFF")))

# Launcher: the night as background, the teal mark in the 66dp safe zone.
write("ic_launcher_background.xml", vector(108, 108, '    <path android:fillColor="' + NIGHT + '" android:pathData="M0,0h108v108h-108z" />\n'))
write("ic_launcher_foreground.xml", vector(108, 108, mark(54, 54, 1.15, TEAL)))
write("ic_launcher_monochrome.xml", vector(108, 108, mark(54, 54, 1.15, "#FFFFFFFF")))

# Splash: the play button appears, then its echoes go out one after another.
targets = '''    <target android:name="play">
        <aapt:attr name="android:animation">
            <set>
                <objectAnimator android:duration="260" android:propertyName="fillAlpha" android:valueFrom="0" android:valueTo="1" android:valueType="floatType" />
                <objectAnimator android:duration="260" android:propertyName="strokeAlpha" android:valueFrom="0" android:valueTo="1" android:valueType="floatType" />
            </set>
        </aapt:attr>
    </target>
'''
for i, (_, _, alpha) in enumerate(ECHOES):
    targets += f'''    <target android:name="echo{i}">
        <aapt:attr name="android:animation">
            <objectAnimator
                android:duration="320"
                android:interpolator="@android:interpolator/fast_out_slow_in"
                android:propertyName="strokeAlpha"
                android:startOffset="{220 + i * 170}"
                android:valueFrom="0"
                android:valueTo="{alpha}"
                android:valueType="floatType" />
        </aapt:attr>
    </target>
'''
splash = f'''<?xml version="1.0" encoding="utf-8"?>
{HEAD}
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt">
    <aapt:attr name="android:drawable">
        <vector
            android:width="288dp" android:height="288dp"
            android:viewportWidth="288" android:viewportHeight="288">
{mark(144, 144, 3.1, TEAL, indent=12, names=True, hidden=True)}        </vector>
    </aapt:attr>
{targets}</animated-vector>
'''
write("splash_pulse.xml", splash)

for f in ["ic_launcher.xml", "ic_launcher_round.xml"]:
    p = RES + "mipmap-anydpi-v26/" + f
    t = open(p, encoding="utf-8").read().replace("@color/ic_launcher_background", "@drawable/ic_launcher_background")
    open(p, "w", encoding="utf-8", newline="\n").write(t)

# Splash and window background: the night.
p = RES + "values/ic_launcher_background.xml"
t = open(p, encoding="utf-8").read()
for old in ["#070A12", "#0C0B11"]:
    t = t.replace(old, "#" + NIGHT[3:])
open(p, "w", encoding="utf-8", newline="\n").write(t)
print("ok")
